import test from 'node:test';
import assert from 'node:assert/strict';
import { promises as fs } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { prepareProjectContext, refreshProjectContext, readProjectContext } from '../core/project-context.js';
import { readOnlyTools, updateHandoffTool } from '../core/tools.js';
import type { AgentContext, FactoryIssueState } from '../core/types.js';

const exec = promisify(execFile);
test('project instructions, customized skills and handoff notes survive refresh and cleanup', async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'factory-context-'));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  const repo = path.join(root, 'repo'), source = path.join(root, 'source');
  await fs.mkdir(repo);
  await exec('git', ['init', '-q', repo]);
  await fs.writeFile(path.join(repo, 'AGENTS.md'), 'Project-specific instructions\n');
  await fs.writeFile(path.join(repo, 'CLAUDE.md'), 'Existing Claude instructions\n');
  await exec('git', ['add', '.'], { cwd: repo });
  await exec('git', ['-c', 'user.name=Test', '-c', 'user.email=test@example.com', 'commit', '-qm', 'initial'], { cwd: repo });
  await fs.cp(path.resolve('skills'), source, { recursive: true });
  const resource = path.join(source, 'spec', 'references', 'example.bin');
  await fs.mkdir(path.dirname(resource), { recursive: true });
  await fs.writeFile(resource, Buffer.from([0, 255, 128]));
  const skillsRoot = await prepareProjectContext(repo, source);
  const ctx = { repo: { workdir: repo }, skillsRoot, skills: [], issue: { number: 72, title: 'Feedback',
    body: 'Use SQLite', comments: [] }, runId: 'first-run', agentId: 'review-spec',
    projectContextFiles: ['AGENTS.md', 'CLAUDE.md', 'factory/AGENTS.md'] } as unknown as AgentContext;
  const state = { issue: ctx.issue, merged: false } as FactoryIssueState;
  await refreshProjectContext(ctx, state, 'review-spec');
  (state as any).review = {verdict:'APPROVE',body:'LARGE-REVIEW-'.repeat(20000),generatedReview:{body:'REPEATED-REVIEW-'.repeat(20000)}};
  (state as any).correction = {targetStage:'verify',turns:['DETAILED-RECOVERY-'.repeat(20000)]};
  state.agentRuntimeFailure = {stage:'verify',code:'FACTORY_AGENT_CONTEXT_EXHAUSTED',message:'Prompt is too long',at:'2026-10-09T07:00:00Z'};
  (state as any).validationFailure = {command:'npm test',timedOut:true,stdout:'Last successful assertion',cwd:repo,profile:'test'};
  ctx.correction = (state as any).correction;
  await refreshProjectContext(ctx,state,'verify-behavior');
  const shared = await fs.readFile(path.join(repo,'factory','AGENTS.md'),'utf8');
  assert.ok(shared.length < 12000,'Shared instructions must not embed full reports and repair transcripts');
  assert.match(shared,/factory\/checkpoint.json/);
  const details = JSON.parse(await fs.readFile(path.join(repo,'factory','checkpoint.json'),'utf8'));
  assert.equal(details.review.body,(state as any).review.body,'Full evidence remains available on demand');
  assert.equal(details.correction.turns[0],(state as any).correction.turns[0]);
  assert.deepEqual(details.agentRuntimeFailure,state.agentRuntimeFailure);
  assert.deepEqual(details.validationFailure,state.validationFailure);
  assert.ok(readOnlyTools(ctx).some(tool => tool.name === 'update_handoff'));
  assert.ok(!readOnlyTools(ctx).some(tool => tool.name === 'write_file'));
  await updateHandoffTool().execute({ note: 'SQLite schema is in src/db.ts.\nNext: check migration.' }, ctx);
  const longNote='Important historical observation.\n'.repeat(2000);
  const handoff:any=await updateHandoffTool().execute({note:longNote},ctx);
  assert.equal(await fs.readFile(path.join(repo,handoff.detailsFile),'utf8'),longNote.trim());
  assert.ok((await fs.readFile(path.join(repo,'factory/AGENTS.md'),'utf8')).length<18000);
  const custom = path.join(skillsRoot, 'review-spec', 'SKILL.md');
  await fs.writeFile(custom, 'Custom project review rubric');
  const updatedSource = path.join(source, 'spec', 'SKILL.md');
  await fs.appendFile(updatedSource, '\nUpdated packaged rule\n');
  await fs.writeFile(resource, Buffer.from([0, 254, 129]));
  await prepareProjectContext(repo, source);
  await refreshProjectContext({ ...ctx, runId: 'next-run', agentId: 'implementation' }, state, 'implementation');
  assert.equal(await fs.readFile(path.join(repo, 'AGENTS.md'), 'utf8'), 'Project-specific instructions\n');
  assert.equal(await fs.readFile(path.join(repo, 'CLAUDE.md'), 'utf8'), 'Existing Claude instructions\n');
  assert.equal(await fs.readFile(custom, 'utf8'), 'Custom project review rubric');
  assert.match(await fs.readFile(path.join(skillsRoot, 'spec', 'SKILL.md'), 'utf8'), /Updated packaged rule/);
  assert.deepEqual(await fs.readFile(path.join(skillsRoot, 'spec', 'references', 'example.bin')), Buffer.from([0, 254, 129]));
  const background = await readProjectContext(ctx);
  assert.match(background, /Project-specific instructions/);
  assert.match(background, /Existing Claude instructions/);
  assert.match(background, /SQLite schema is in src\/db.ts/);
  assert.match(background, /next-run/);
  assert.equal(background.match(/FACTORY_CONTEXT_START/g)?.length, 1);
  await assert.rejects(updateHandoffTool().execute({ note: '<!-- FACTORY_CONTEXT_END -->' }, ctx), /reserved/);
  assert.equal((await exec('git', ['status', '--porcelain'], { cwd: repo })).stdout, '');
  await exec('git', ['clean', '-fd'], { cwd: repo });
  assert.match(await fs.readFile(path.join(repo, 'factory', 'AGENTS.md'), 'utf8'), /SQLite schema/);
  await fs.rm(path.join(repo, 'factory', 'AGENTS.md'));
  await assert.rejects(readProjectContext(ctx), { code: 'FACTORY_STATE_CONTEXT_UNAVAILABLE' });
});

test('tracked project skills remain authoritative even if previously generated', async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'factory-tracked-skill-'));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  await exec('git', ['init', '-q', root]);
  await prepareProjectContext(root, path.resolve('skills'));
  await exec('git', ['add', '-f', 'skills/spec/SKILL.md'], { cwd: root });
  const file = path.join(root, 'skills', 'spec', 'SKILL.md');
  const body = await fs.readFile(file, 'utf8');
  await prepareProjectContext(root, path.resolve('skills'));
  assert.equal(await fs.readFile(file, 'utf8'), body);
  assert.equal((await exec('git', ['diff', '--', 'skills/spec/SKILL.md'], { cwd: root })).stdout, '');
});

test('context materialization refuses a worktree symlink that escapes the project', async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'factory-context-link-'));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  const repo = path.join(root, 'repo'), outside = path.join(root, 'outside');
  await fs.mkdir(repo); await fs.mkdir(outside);
  await exec('git', ['init', '-q', repo]);
  await fs.symlink(outside, path.join(repo, 'skills'), process.platform === 'win32' ? 'junction' : 'dir');
  await assert.rejects(prepareProjectContext(repo, path.resolve('skills')), /Symlink escapes repository/);
  assert.deepEqual(await fs.readdir(outside), []);
});
